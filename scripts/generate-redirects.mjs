#!/usr/bin/env node
/**
 * Generates public/_redirects from src/data/redirects.mjs.
 *
 * Cloudflare Pages reads _redirects at deploy time. Generating it means the
 * redirect map is reviewed as source, duplicates are caught here rather than in
 * production, and the file cannot drift from the map.
 *
 * Cloudflare limits a project to 2100 redirect rules, of which 100 may be
 * dynamic (containing a splat or placeholder). Both limits are checked.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { redirects } from '../src/data/redirects.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'public', '_redirects');

const STATIC_LIMIT = 2100;
const DYNAMIC_LIMIT = 100;

const isDynamic = (rule) => rule.from.includes('*') || rule.from.includes(':');

function validate(rules) {
  const problems = [];

  const seen = new Map();
  for (const rule of rules) {
    if (!rule.from.startsWith('/')) {
      problems.push(`"from" must start with a slash: ${rule.from}`);
    }
    if (seen.has(rule.from)) {
      problems.push(`duplicate source route: ${rule.from}`);
    }
    seen.set(rule.from, rule.to);

    // A rule pointing at itself is a redirect loop in production.
    if (rule.from === rule.to) {
      problems.push(`redirect loop, source equals target: ${rule.from}`);
    }
  }

  const dynamic = rules.filter(isDynamic).length;
  if (dynamic > DYNAMIC_LIMIT) {
    problems.push(`${dynamic} dynamic rules exceeds the Cloudflare limit of ${DYNAMIC_LIMIT}`);
  }
  if (rules.length > STATIC_LIMIT) {
    problems.push(`${rules.length} rules exceeds the Cloudflare limit of ${STATIC_LIMIT}`);
  }

  return problems;
}

const problems = validate(redirects);
if (problems.length) {
  console.error('Redirect map is invalid:');
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

// Cloudflare evaluates rules top to bottom and stops at the first match, so
// specific routes must precede the wildcards that would otherwise swallow them.
const ordered = [...redirects].sort((a, b) => {
  if (isDynamic(a) !== isDynamic(b)) return isDynamic(a) ? 1 : -1;
  return b.from.length - a.from.length;
});

const lines = [
  '# Generated by scripts/generate-redirects.mjs. Do not edit.',
  '# Source of truth: src/data/redirects.mjs',
  '',
  ...ordered.map((r) => `${r.from}  ${r.to}  ${r.status ?? 301}`),
  '',
];

await writeFile(OUT, lines.join('\n'), 'utf8');

const dynamic = redirects.filter(isDynamic).length;
console.log(
  `_redirects written: ${redirects.length} rules (${dynamic} dynamic, ${redirects.length - dynamic} static).`
);
